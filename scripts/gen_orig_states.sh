#!/usr/bin/env sh
# Generates src/orig/orig_states.c and src/orig/orig_states.h from the
# statetype tables in reference/original/WL_ACT2.C (non-SPEAR, non-UPLOAD
# build). Run from the repository root:  sh scripts/gen_orig_states.sh
set -eu

src=reference/original/WL_ACT2.C
out_c=src/orig/orig_states.c
out_h=src/orig/orig_states.h

# Keep only the lines the original build compiled. SPEAR and UPLOAD are not
# defined, so #ifdef blocks are dropped and #ifndef blocks kept; #else flips.
active_lines() {
    tr -d '\r' < "$src" | awk '
    function active(  i) { for (i = 1; i <= depth; i++) if (!on[i]) return 0; return 1 }
    /^#ifdef[[:space:]]/  { depth++; on[depth] = 0; next }
    /^#ifndef[[:space:]]/ { depth++; on[depth] = 1; next }
    /^#else/              { on[depth] = !on[depth]; next }
    /^#endif/             { depth--; next }
    active() { print }'
}

states=$(active_lines | grep -E '^statetype[[:space:]]+s_[A-Za-z0-9_]+[[:space:]]*=' \
    | sed -E 's/[[:space:]]+/ /g; s/ *= */ = /; s/ *;.*$/;/; s/\{ */{/; s/ *\}/}/; s/ *, */, /g')

names=$(printf '%s\n' "$states" | sed -E 's/^statetype (s_[A-Za-z0-9_]+) = .*/\1/')

funcs=$(printf '%s\n' "$states" \
    | sed -E 's/^[^{]*\{[^,]*, [^,]*, [^,]*, ([^,]*), ([^,]*), .*/\1 \2/' \
    | tr ' ' '\n' | grep -v '^NULL$' | sort -u)

{
    echo '#pragma once'
    echo
    echo '/* Generated by scripts/gen_orig_states.sh from WL_ACT2.C. Do not edit. */'
    echo
    echo '#include "orig_def.h"'
    echo
    printf '%s\n' "$funcs" | sed 's/.*/void &(objtype *ob);/'
    echo
    printf '%s\n' "$names" | sed 's/.*/extern statetype &;/'
    echo
    echo '/* Every state above, in source order (tests, save games). */'
    echo 'extern statetype *const orig_statelist[];'
    echo 'extern const int orig_numstates;'
} > "$out_h"

{
    echo '/* Generated by scripts/gen_orig_states.sh from WL_ACT2.C. Do not edit. */'
    echo '#include "orig_states.h"'
    echo
    echo '#include "orig_spr.h"'
    echo
    printf '%s\n' "$states"
    echo
    echo 'statetype *const orig_statelist[] = {'
    printf '%s\n' "$names" | sed 's/.*/    \&&,/'
    echo '};'
    echo
    echo 'const int orig_numstates = (int)(sizeof(orig_statelist) / sizeof(orig_statelist[0]));'
} > "$out_c"

echo "$(printf '%s\n' "$names" | wc -l) states, $(printf '%s\n' "$funcs" | wc -l) functions"
