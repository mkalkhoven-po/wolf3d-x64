"""Draws the Wolf3D x64 icon, pixel by pixel, and writes it out.

The icon is original pixel art (a gold chalice on a blue stone wall), not id
Software's artwork: Wolfenstein is a ZeniMax trademark. It is drawn at 32x32;
the other sizes take the nearest pixel (64, 128 and 256 are whole multiples,
16 takes every other pixel).

    python scripts/make_icon.py

writes res/wolf3d-x64.ico (16-256 pixels, PNG entries) and
src/platform/win_sdl/wolf_icon.c (the 32x32 picture for SDL_SetWindowIcon).
Run it again after changing the drawing and commit both files.
"""
import os
import struct
import zlib

N = 32
CLEAR = (0, 0, 0, 0)

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def canvas():
    return [[CLEAR for _ in range(N)] for _ in range(N)]


def rect(img, x0, y0, x1, y1, c):
    for y in range(max(0, y0), min(N, y1 + 1)):
        for x in range(max(0, x0), min(N, x1 + 1)):
            img[y][x] = c


def px(img, x, y, c):
    if 0 <= x < N and 0 <= y < N:
        img[y][x] = c


def stone_wall(img):
    """blue stone blocks with dark mortar, lit from the top left"""
    mortar = (22, 30, 70, 255)
    stone = (58, 86, 168, 255)
    light = (96, 124, 206, 255)
    dark = (38, 58, 120, 255)
    rect(img, 0, 0, N - 1, N - 1, mortar)
    for row in range(4):
        y0 = row * 8
        off = 0 if row % 2 == 0 else -6
        for col in range(-1, 4):
            x0 = col * 12 + off
            x1 = x0 + 10
            rect(img, x0, y0, x1, y0 + 6, stone)
            rect(img, x0, y0, x1, y0, light)
            rect(img, x0, y0, x0, y0 + 6, light)
            rect(img, x0 + 1, y0 + 6, x1, y0 + 6, dark)
            rect(img, x1, y0 + 1, x1, y0 + 6, dark)
            px(img, x0 + 4, y0 + 3, dark)
            px(img, x0 + 7, y0 + 2, light)


def outline(img, inside, color):
    """a one-pixel line around every pixel whose colour is in inside"""
    out = [row[:] for row in img]
    for y in range(N):
        for x in range(N):
            if img[y][x] in inside:
                for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)):
                    xx, yy = x + dx, y + dy
                    if 0 <= xx < N and 0 <= yy < N and img[yy][xx] not in inside:
                        out[yy][xx] = color
    return out


def round_corners(img):
    for x, y in ((0, 0), (1, 0), (0, 1), (N - 1, 0), (N - 2, 0), (N - 1, 1), (0, N - 1),
                 (1, N - 1), (0, N - 2), (N - 1, N - 1), (N - 2, N - 1), (N - 1, N - 2)):
        img[y][x] = CLEAR


def draw():
    img = canvas()
    stone_wall(img)
    au = (232, 184, 40, 255)   # gold
    hi = (255, 236, 140, 255)  # shine
    sh = (160, 110, 20, 255)   # shade
    ruby = (200, 30, 40, 255)
    sapphire = (60, 160, 230, 255)
    rect(img, 8, 5, 23, 15, au)      # cup
    rect(img, 9, 15, 22, 16, au)
    rect(img, 11, 17, 20, 18, au)
    rect(img, 14, 19, 17, 23, au)    # stem
    rect(img, 10, 24, 21, 26, au)    # foot
    rect(img, 9, 5, 10, 14, hi)
    rect(img, 15, 20, 15, 22, hi)
    rect(img, 21, 6, 23, 15, sh)
    rect(img, 18, 24, 21, 26, sh)
    rect(img, 8, 5, 23, 5, hi)
    for x, y in ((12, 9), (17, 10), (14, 12), (19, 7)):  # jewels
        px(img, x, y, ruby)
        px(img, x + 1, y, sapphire)
    img = outline(img, (au, hi, sh, ruby, sapphire), (20, 14, 4, 255))
    round_corners(img)
    return img


def resized(img, size):
    """nearest pixel: whole multiples stay sharp; 16 takes every other pixel"""
    return [[img[y * N // size][x * N // size] for x in range(size)] for y in range(size)]


def png_bytes(img):
    h, w = len(img), len(img[0])
    raw = b''.join(b'\x00' + b''.join(bytes(c) for c in row) for row in img)

    def chunk(t, d):
        return struct.pack('>I', len(d)) + t + d + struct.pack('>I', zlib.crc32(t + d) & 0xffffffff)

    return (b'\x89PNG\r\n\x1a\n' + chunk(b'IHDR', struct.pack('>IIBBBBB', w, h, 8, 6, 0, 0, 0)) +
            chunk(b'IDAT', zlib.compress(raw, 9)) + chunk(b'IEND', b''))


def write_ico(path, img, sizes):
    images = [png_bytes(resized(img, s)) for s in sizes]
    header = struct.pack('<HHH', 0, 1, len(sizes))
    offset = 6 + 16 * len(sizes)
    entries = b''
    for s, data in zip(sizes, images):
        entries += struct.pack('<BBBBHHII', s % 256, s % 256, 0, 0, 1, 32, len(data), offset)
        offset += len(data)
    with open(path, 'wb') as f:
        f.write(header + entries + b''.join(images))


def write_c(path, img):
    lines = []
    for row in img:
        lines.append('    ' + ', '.join('0x%02x, 0x%02x, 0x%02x, 0x%02x' % c for c in row) + ',')
    with open(path, 'w', newline='\n') as f:
        f.write('/* Generated by scripts/make_icon.py: the 32x32 window icon, RGBA. Do not edit. */\n\n')
        f.write('#include "wolf_icon.h"\n\n')
        f.write('const unsigned char wolf_icon_rgba[WOLF_ICON_SIZE * WOLF_ICON_SIZE * 4] = {\n')
        f.write('\n'.join(lines) + '\n};\n')


if __name__ == '__main__':
    icon = draw()
    write_ico(os.path.join(ROOT, 'res', 'wolf3d-x64.ico'), icon, (16, 24, 32, 48, 64, 128, 256))
    write_c(os.path.join(ROOT, 'src', 'platform', 'win_sdl', 'wolf_icon.c'), icon)
    print('wrote res/wolf3d-x64.ico and src/platform/win_sdl/wolf_icon.c')
